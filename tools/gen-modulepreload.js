#!/usr/bin/env node
/**
 * Rewrites the <modulepreload> block in engine.html from the real import graph.
 *
 * Why this exists: engine.html loads main.js as a module, and main.js reaches 122 more
 * modules at a graph depth of 5. Without preload hints the browser can only discover
 * each level after parsing the one above it, so a cold boot spends five sequential
 * round-trip generations just finding out what to fetch — and with HTTP/1.1's six
 * connections per origin, the tail of each generation blocks the start of the next.
 * Emitting every reachable module as `rel="modulepreload"` lets the browser queue the
 * whole graph immediately and saturate its connection pool from the first parse.
 *
 * Run after adding or removing imports:
 *     node tools/gen-modulepreload.js
 *
 * The list is regenerated in place between the BEGIN/END markers, so hand edits inside
 * the block will be overwritten — change the graph, not the block.
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const ENTRY = 'main.js';
const TARGET = path.join(ROOT, 'engine.html');

const BEGIN = '<!-- BEGIN modulepreload (generated by tools/gen-modulepreload.js) -->';
const END = '<!-- END modulepreload -->';

const IMPORT_RE = /(?:^|[\s;])(?:import|export)\s[^'"]*?from\s*['"](\.[^'"]+)['"]/g;
const BARE_IMPORT_RE = /(?:^|[\s;])import\s*['"](\.[^'"]+)['"]/g;

function importsOf(absFile) {
    let src;
    try {
        src = fs.readFileSync(absFile, 'utf8');
    } catch {
        return [];
    }
    const dir = path.dirname(absFile);
    const found = new Set();
    for (const re of [IMPORT_RE, BARE_IMPORT_RE]) {
        re.lastIndex = 0;
        let m;
        while ((m = re.exec(src)) !== null) {
            found.add(path.resolve(dir, m[1]));
        }
    }
    return [...found];
}

// Breadth-first so the emitted order matches load order: the modules the entry point
// needs soonest are queued first, which matters once the connection pool saturates.
function collect(entryRel) {
    const entryAbs = path.join(ROOT, entryRel);
    const seen = new Set([entryAbs]);
    const ordered = [];
    let frontier = [entryAbs];

    while (frontier.length > 0) {
        const next = [];
        for (const file of frontier) {
            for (const dep of importsOf(file)) {
                if (seen.has(dep)) continue;
                if (!fs.existsSync(dep)) {
                    console.warn(`  ! unresolved import: ${path.relative(ROOT, dep)} (from ${path.relative(ROOT, file)})`);
                    continue;
                }
                seen.add(dep);
                ordered.push(dep);
                next.push(dep);
            }
        }
        frontier = next;
    }
    return ordered.map(p => path.relative(ROOT, p).split(path.sep).join('/'));
}

const modules = collect(ENTRY);
const block = [
    BEGIN,
    ...modules.map(m => `    <link rel="modulepreload" href="${m}">`),
    `    ${END}`
].join('\n');

const html = fs.readFileSync(TARGET, 'utf8');
const beginIdx = html.indexOf(BEGIN);
const endIdx = html.indexOf(END);

if (beginIdx === -1 || endIdx === -1) {
    console.error(`Could not find the modulepreload markers in ${path.relative(ROOT, TARGET)}.`);
    console.error(`Insert these two lines in <head> and re-run:\n  ${BEGIN}\n  ${END}`);
    process.exit(1);
}

const updated = html.slice(0, beginIdx) + block + html.slice(endIdx + END.length);
fs.writeFileSync(TARGET, updated);
console.log(`Wrote ${modules.length} modulepreload hints into ${path.relative(ROOT, TARGET)}.`);
